/**
 * Binary Heap
 * Binary Heap is a complete binary tree that satisfies the heap property.
 * The heap property is that the value of a node is greater than or equal to (in a max heap) or less than or equal to (in a min heap) the values of its parent, with the maximum value in the root (in a max heap) or the minimum value in the root (in a min heap).
 * There are two types of Binary Heap:
 * 1. Max-Heap: In a Max-Heap the key present at the root node must be greatest among the keys present at all of it's children.
 * The same property must be recursively true for all sub-trees in that Binary Tree.
 * 2. Min-Heap: In a Min-Heap the key present at the root node must be minimum among the keys present at all of it's children.
 * The same property must be recursively true for all sub-trees in that Binary Tree.
 */
