// question 1
// Write a function that takes a string as an argument and returns a new string that is the old string with the first letter of every word capitalized.
// For example, if the argument is "hello world", the function should return "Hello World".
// The function should work for both uppercase and lowercase letters.
// The function should not change the original string.

function capitalize(str) {
  return str
    .split(" ")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");
}

console.log(capitalize("hello world"));

